
# items add in list

"""

Append Items
To add an item to the end of the list, use the append() method:

Insert Items
To insert a list item at a specified index, use the insert() method.
"""

# append method

name = ["Bayjid Alom", "Jubaeid Alom", "Babul Mia"]
print(name)
name.append("Jihad")
print(name)


# insert method

name.insert(0, "Position 0")
print(name)

name.insert(3, "Position 3")
print(name)

name.insert(2, "Position 2")
print(name)